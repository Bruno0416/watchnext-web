// ---------- utilidades html ----------
export function escapeHtml(value) {
  // 1. escapar caracteres con significado especial en html
  return String(value ?? "").replace(
    /[&<>"']/g,
    (character) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#039;",
      })[character],
  );
}
